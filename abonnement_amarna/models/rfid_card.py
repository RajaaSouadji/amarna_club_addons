# -*- coding: utf-8 -*-
from odoo import api, fields, models
from odoo.exceptions import ValidationError

EMPTY_NAMES = ('', '/', 'New', 'Nouveau')


class AmarnaRfidCard(models.Model):
    """Badge of a member.

    One card per member. The card is scanned once on the member's sheet; from
    then on every subscription and reservation of that member uses it. Whether
    the card opens the door right now is never typed in: it follows from the
    authorisations generated by the paid subscriptions and reservations (see
    ``amarna.rfid.access``), which the card form lists in a tab.
    """
    _name = 'amarna.rfid.card'
    _description = 'Carte RFID membre'
    _order = 'name'

    name = fields.Char(
        string='Numéro de la carte', required=True, index=True, copy=False, default='/',
        help="Numéro lu par le lecteur : passez la carte devant le lecteur, ou saisissez-le. "
             "Laissé vide, un numéro interne est généré.")
    partner_id = fields.Many2one('res.partner', string='Membre', ondelete='set null', index=True)
    restriction = fields.Selection(
        [('lost', 'Perdue'), ('blocked', 'Bloquée')], string='Restriction', copy=False,
        help="Posée à la main quand la carte est perdue ou volée, ou pour bloquer un membre. "
             "Tant qu'elle est posée, la carte n'ouvre aucun accès.")
    state = fields.Selection([
        ('inactive', 'Sans accès'), ('active', 'Accès ouvert'),
        ('lost', 'Perdue'), ('blocked', 'Bloquée'),
    ], string='État', compute='_compute_state', store=True,
        help="Jamais saisi : « Perdue » et « Bloquée » viennent de la restriction posée à la main ; "
             "sinon « Accès ouvert » quand une autorisation d'accès est en cours (abonnement ou "
             "réservation payé), « Sans accès » dans le cas contraire.")
    assigned_date = fields.Date(string='Date d’attribution', default=fields.Date.today)
    access_ids = fields.One2many('amarna.rfid.access', 'card_id', string='Autorisations d’accès', readonly=True)
    checkin_ids = fields.One2many('amarna.checkin', 'rfid_card_id', string='Passages', readonly=True)
    access_until = fields.Datetime(string='Accès jusqu’au', compute='_compute_current_access')
    access_source = fields.Char(string='Accès accordé par', compute='_compute_current_access')
    note = fields.Text(string='Notes')
    company_id = fields.Many2one('res.company', default=lambda self: self.env.company, required=True)

    _rfid_name_unique = models.Constraint(
        'unique(name)', 'Cette carte existe déjà : un numéro ne peut être utilisé que pour une seule carte.')

    @api.depends('access_ids.state', 'access_ids.start_datetime', 'access_ids.end_datetime')
    def _compute_current_access(self):
        now = fields.Datetime.now()
        for card in self:
            current = card.access_ids.filtered(
                lambda a: a.state in ('scheduled', 'active') and a.start_datetime <= now <= a.end_datetime
            ).sorted('end_datetime', reverse=True)[:1]
            card.access_until = current.end_datetime or False
            card.access_source = current.name or False

    @api.depends('restriction', 'access_ids.state', 'access_ids.active',
                 'access_ids.start_datetime', 'access_ids.end_datetime')
    def _compute_state(self):
        now = fields.Datetime.now()
        for card in self:
            if card.restriction:
                card.state = card.restriction
            elif card.access_ids.filtered(
                    lambda a: a.active and a.state in ('scheduled', 'active')
                    and a.start_datetime <= now <= a.end_datetime):
                card.state = 'active'
            else:
                card.state = 'inactive'

    # ---------------------------------------------------------------- CRUD

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            name = (vals.get('name') or '').strip()
            if name in EMPTY_NAMES:
                name = self.env['ir.sequence'].next_by_code('amarna.rfid.card') or 'RFID00001'
            vals['name'] = name
        cards = super().create(vals_list)
        cards._link_to_member_records()
        return cards

    def write(self, vals):
        if 'name' in vals:
            vals['name'] = (vals['name'] or '').strip() or self.env['ir.sequence'].next_by_code('amarna.rfid.card')
        result = super().write(vals)
        if 'partner_id' in vals:
            self._link_to_member_records()
        return result

    @api.constrains('partner_id')
    def _check_one_card_per_member(self):
        for card in self.filtered('partner_id'):
            duplicate = self.search_count([('partner_id', '=', card.partner_id.id), ('id', '!=', card.id)])
            if duplicate:
                raise ValidationError('Un membre ne peut avoir qu’une seule carte RFID attribuée.')

    def _link_to_member_records(self):
        """A card given to a member serves all that member's current subscriptions and
        bookings that have no card yet: nobody has to pick the card again, one by one."""
        now = fields.Datetime.now()
        for card in self.filtered('partner_id'):
            self.env['amarna.subscription'].search([
                ('partner_id', '=', card.partner_id.id), ('rfid_card_id', '=', False),
                ('state', 'in', ('draft', 'confirmed')),
            ]).write({'rfid_card_id': card.id})
            self.env['amarna.club.reservation'].search([
                ('partner_id', '=', card.partner_id.id), ('rfid_card_id', '=', False),
                ('status', 'in', ('pending', 'confirmed')), ('end_at', '>=', now),
            ]).write({'rfid_card_id': card.id})

    # --------------------------------------------------------------- State

    def _sync_access_state(self):
        """Recompute the state: authorisations start and end with the clock, not only
        when a record changes."""
        self.env.add_to_compute(self._fields['state'], self)
        self.mapped('state')

    def action_open_scan(self):
        """Check this card at the door: opens the scan screen already filled with it."""
        self.ensure_one()
        wizard = self.env['amarna.scan.wizard'].create({'card_code': self.name, 'card_id': self.id})
        action = wizard.action_scan()
        action['name'] = 'Scanner une carte RFID'
        return action

    def action_block(self):
        self.write({'restriction': 'blocked'})

    def action_lost(self):
        self.write({'restriction': 'lost'})

    def action_restore(self):
        """Lift a block / a loss declaration: the state follows the authorisations again."""
        self.write({'restriction': False})

    def action_unassign(self):
        self.write({'partner_id': False})
